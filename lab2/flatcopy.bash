#!/usr/bin/env bash
#
# flatcopy.bash — «плоское» копирование обычных файлов.
#
# НАЗНАЧЕНИЕ
#   Копирует все обычные файлы (regular files) из исходной директории и всех
#   её поддиректорий в целевую директорию. Структура поддиректорий НЕ
#   воспроизводится: все файлы оказываются непосредственно в целевой
#   директории. Если встречаются файлы с одинаковыми именами, выдаётся
#   предупреждение, а в целевой директории остаётся последний обработанный
#   файл.
#
# ИСПОЛЬЗОВАНИЕ
#   flatcopy.bash [-h] [-v] [-n] [-p] <исходная_директория> <целевая_директория>
#
# МОДИФИКАТОРЫ (POSIX.2, разбираются через getopts)
#   -h  (help)     вывести краткую справку и завершить работу;
#   -v  (verbose)  выводить информацию о каждом копируемом файле;
#   -n  (no-op)    «пробный прогон»: показать, что будет сделано,
#                  но ничего не копировать (подразумевает -v);
#   -p  (parents)  создать целевую директорию (вместе с родительскими),
#                  если она не существует.
#
# ВХОДНЫЕ АРГУМЕНТЫ
#   <исходная_директория>  существующая директория, доступная для чтения;
#   <целевая_директория>   существующая (или создаваемая с -p) директория,
#                          доступная для записи; не должна совпадать
#                          с исходной.
#
# ОСОБЕННОСТИ
#   * Символические ссылки, устройства, каналы и т.п. не копируются —
#     только обычные файлы.
#   * Если целевая директория находится внутри исходной, её содержимое
#     при обходе пропускается (чтобы не копировать файлы сами в себя).
#   * Имена файлов могут содержать пробелы, переводы строк и любые
#     спецсимволы (используется find -print0).
#
# КОДЫ ВОЗВРАТА
#   0 — успешно;
#   1 — ошибка при копировании одного или нескольких файлов;
#   2 — неверные модификаторы или аргументы.

PROG=${0##*/}

usage() {
    cat <<EOF
Использование: $PROG [-h] [-v] [-n] [-p] <исходная_директория> <целевая_директория>

Копирует обычные файлы из исходной директории и всех её поддиректорий
в целевую директорию без сохранения структуры поддиректорий.
При совпадении имён выдаётся предупреждение и остаётся последний файл.

Модификаторы:
  -h   показать эту справку и выйти
  -v   подробный вывод (каждый копируемый файл)
  -n   пробный прогон: ничего не копировать, только показать действия
  -p   создать целевую директорию, если она не существует
EOF
}

# Сообщение об ошибке использования + подсказка, выход с кодом 2.
usage_error() {
    echo "$PROG: $1" >&2
    echo "Справка: $PROG -h" >&2
    exit 2
}

warn() {
    echo "$PROG: предупреждение: $1" >&2
}

# ---------- Разбор модификаторов ----------

verbose=0
dry_run=0
make_dst=0

while getopts ":hvnp" opt; do
    case $opt in
        h) usage; exit 0 ;;
        v) verbose=1 ;;
        n) dry_run=1; verbose=1 ;;
        p) make_dst=1 ;;
        \?) usage_error "неизвестный модификатор -- '$OPTARG'" ;;
    esac
done
shift $((OPTIND - 1))

# ---------- Проверка аргументов ----------

[ $# -lt 2 ] && usage_error "не хватает аргументов (ожидается 2, получено $#)"
[ $# -gt 2 ] && usage_error "слишком много аргументов (ожидается 2, получено $#)"

src=$1
dst=$2

[ -z "$src" ] && usage_error "исходная директория задана пустой строкой"
[ -z "$dst" ] && usage_error "целевая директория задана пустой строкой"

[ -e "$src" ] || usage_error "'$src': исходная директория не существует"
[ -d "$src" ] || usage_error "'$src': не является директорией"
[ -r "$src" ] && [ -x "$src" ] || usage_error "'$src': нет прав на чтение директории"

if [ ! -e "$dst" ]; then
    if [ $make_dst -eq 1 ]; then
        if [ $dry_run -eq 1 ]; then
            echo "создание директории '$dst'"
        else
            mkdir -p -- "$dst" || usage_error "'$dst': не удалось создать директорию"
        fi
    else
        usage_error "'$dst': целевая директория не существует (используйте -p для создания)"
    fi
fi

if [ -e "$dst" ]; then
    [ -d "$dst" ] || usage_error "'$dst': не является директорией"
    [ -w "$dst" ] && [ -x "$dst" ] || usage_error "'$dst': нет прав на запись в директорию"
fi

# Абсолютные физические пути (без символических ссылок) для сравнения.
src_abs=$(cd -P -- "$src" && pwd -P) || exit 2
if [ -d "$dst" ]; then
    dst_abs=$(cd -P -- "$dst" && pwd -P) || exit 2
else
    # Директория ещё не создана (пробный прогон с -p).
    dst_abs=$(cd -P -- "$(dirname -- "$dst")" 2>/dev/null && pwd -P)/$(basename -- "$dst")
fi

[ "$src_abs" = "$dst_abs" ] && usage_error "исходная и целевая директории совпадают"

# ---------- Основной алгоритм ----------

# Множество уже обработанных имён. Имя файла не может содержать '/',
# поэтому храним его в строке вида "/имя1/имя2/" — это работает и в
# bash 3.2 (macOS), где нет ассоциативных массивов.
seen="/"
copied=0
duplicates=0
errors=0

while IFS= read -r -d '' file; do
    # Метка ошибки обхода от find (см. конец цикла). Все пути от find
    # абсолютные и начинаются с '/', поэтому с файлом её не спутать.
    if [ "$file" = "find-error" ]; then
        errors=$((errors + 1))
        continue
    fi

    # Пропускаем содержимое целевой директории, если она внутри исходной.
    case $file in
        "$dst_abs"/*) continue ;;
    esac

    name=${file##*/}

    case $seen in
        *"/$name/"*)
            duplicates=$((duplicates + 1))
            warn "дубликат имени '$name': '$file' заменяет ранее скопированный файл"
            ;;
        *)
            seen="$seen$name/"
            ;;
    esac

    target="$dst_abs/$name"

    # В целевой директории под этим именем уже лежит не обычный файл
    # (поддиректория, ссылка и т.п.) — cp положил бы файл внутрь
    # или записал бы по ссылке, поэтому пропускаем.
    if [ -L "$target" ] || { [ -e "$target" ] && [ ! -f "$target" ]; }; then
        errors=$((errors + 1))
        echo "$PROG: ошибка: '$target' существует и не является обычным файлом, '$file' пропущен" >&2
        continue
    fi

    [ $verbose -eq 1 ] && echo "'$file' -> '$target'"

    if [ $dry_run -eq 0 ]; then
        if cp -f -p -- "$file" "$target"; then
            copied=$((copied + 1))
        else
            errors=$((errors + 1))
        fi
    else
        copied=$((copied + 1))
    fi
done < <(find "$src_abs" -type f -print0 || printf 'find-error\0')

if [ $verbose -eq 1 ]; then
    [ $dry_run -eq 1 ] && action="будет скопировано" || action="скопировано"
    echo "Итого: $action файлов: $copied, дубликатов имён: $duplicates, ошибок: $errors"
fi

[ $errors -eq 0 ] || exit 1
exit 0
